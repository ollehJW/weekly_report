const assert = require('node:assert/strict');
const { chromium } = require(process.env.WIAREPORT_PLAYWRIGHT_MODULE || 'playwright-core');
(async () => {
  const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
  const page = await browser.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(process.env.WIAREPORT_TEST_URL || 'http://127.0.0.1:18103');
  await page.getByLabel('ID', { exact: true }).fill('browser-admin');
  await page.getByLabel('비밀번호', { exact: true }).fill('Browser-admin-test!2026');
  await page.getByRole('button', { name: '로그인', exact: true }).click();
  await page.getByRole('button', { name: '계정 관리', exact: true }).click();
  await page.getByPlaceholder('소속', { exact: true }).fill('브라우저 검증');
  await page.getByPlaceholder('ID', { exact: true }).fill('browser-created');
  await page.getByRole('button', { name: '계정 부여', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: '임시 비밀번호 발급' });
  await dialog.waitFor();
  const input = dialog.getByLabel('발급된 임시 비밀번호');
  assert.equal(await input.getAttribute('type'), 'password');
  const temporary = await input.inputValue();
  assert(temporary.length >= 32);
  assert(!(await page.locator('body').textContent()).includes(temporary));
  const downloaded = page.waitForEvent('download');
  await dialog.getByRole('button', { name: '전달용 파일 다운로드' }).click();
  const download = await downloaded;
  const stream = await download.createReadStream();
  const chunks=[];for await (const chunk of stream) chunks.push(chunk);
  assert(Buffer.concat(chunks).toString('utf8').includes(temporary));
  await download.delete();
  await dialog.getByRole('button', { name: '닫기', exact: true }).click();
  await page.getByRole('button', { name: '로그아웃', exact: true }).click();
  await page.getByLabel('ID', { exact: true }).fill('browser-created');
  await page.getByLabel('비밀번호', { exact: true }).fill(temporary);
  await page.getByRole('button', { name: '로그인', exact: true }).click();
  await page.getByLabel('새 비밀번호 (12자 이상)', { exact: true }).fill('Browser-new-password!2026');
  await page.getByLabel('새 비밀번호 확인', { exact: true }).fill('Browser-new-password!2026');
  await page.getByRole('button', { name: '로그인', exact: true }).click();
  await page.getByRole('button', { name: '비밀번호 변경', exact: true }).click();
  const change = page.getByRole('dialog', { name: '비밀번호 변경' });
  await change.getByPlaceholder('현재 비밀번호', { exact: true }).fill('Browser-new-password!2026');
  await change.getByPlaceholder('새 비밀번호', { exact: true }).fill('Browser-changed-password!2026');
  await change.getByPlaceholder('새 비밀번호 확인', { exact: true }).fill('Browser-changed-password!2026');
  await change.getByRole('button', { name: '변경', exact: true }).click();
  await change.waitFor({ state: 'hidden' });
  assert.deepEqual(errors, []);
  await browser.close();
  console.log('PASS: admin issuance, masked credential display, explicit download, temporary login activation, own password change; no page errors');
})().catch(error => {console.error(error);process.exit(1)});
